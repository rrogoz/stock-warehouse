"""Generate the silver dbt models from the entity configs (docs/specs/SW-19.md, ADR-007).

Run as `uv run python -m engine.dbt_models` after changing a file in `config/entities/`. The SQL
comes from the dbt macro `silver_entity()`; this writes only, per `dbt` entity, a one-line
stub and the model's yml (contract, tests and the `meta` the macro reads), because dbt cannot
derive a contract and tests from a macro. Output is byte-stable; `--check` writes nothing.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
ENTITY_DIR = ROOT / "config" / "entities"
OUT_DIR = ROOT / "dbt" / "models" / "silver"
STANDARD = ("known_at", "run_id", "record_hash")
STUB = "{{{{ silver_entity('{input}') }}}}\n"
HEADER = (
    "# Generated by `python -m engine.dbt_models` from config/entities/{entity}.yaml;"
    " do not edit.\n"
)
# Entity config type to the DuckDB type dbt checks the contract against.
DATA_TYPES = {
    "varchar": "varchar",
    "date": "date",
    "timestamptz": "timestamp with time zone",
    "boolean": "boolean",
    "json": "json",
}


def load_entities(entity_dir: Path = ENTITY_DIR) -> list[dict[str, Any]]:
    return [
        yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(entity_dir.glob("*.yaml"))
    ]


def key_fields(entity: dict[str, Any]) -> list[str]:
    """Business key, plus `valid_from_date` for an SCD2 entity (ADR-004)."""
    key = list(entity["business_key"])
    return key + ["valid_from_date"] if entity["scd2"] else key


def value_fields(entity: dict[str, Any]) -> list[str]:
    key = key_fields(entity)
    return [f["name"] for f in entity["fields"] if f["name"] not in key + list(STANDARD)]


def _column(field: dict[str, Any]) -> dict[str, Any]:
    tests: list[Any] = []
    if field["required"]:
        tests.append("not_null")
    if "allowed" in field:
        tests.append({"accepted_values": {"arguments": {"values": field["allowed"]}}})
    if "references" in field:
        entity, column = field["references"].split(".")
        tests.append({"relationships": {"arguments": {"to": f"ref('{entity}')", "field": column}}})
    column_spec: dict[str, Any] = {
        "name": field["name"],
        "data_type": DATA_TYPES[field["type"]],
        "description": field["description"],
    }
    if tests:
        column_spec["data_tests"] = tests
    return column_spec


def model_yml(entity: dict[str, Any]) -> str:
    name = entity["entity"]
    model = {
        "name": name,
        "description": " ".join(entity["description"].split()) + f" Grain: {entity['grain']}.",
        "config": {
            "materialized": "incremental",
            "incremental_strategy": "append",
            "on_schema_change": "fail",
            "contract": {"enforced": True},
            "meta": {
                "key": key_fields(entity),
                "values": value_fields(entity),
            },
        },
        "data_tests": [
            {"unique_key": {"arguments": {"columns": key_fields(entity) + ["known_at"]}}}
        ],
        "columns": [_column(field) for field in entity["fields"]],
    }
    body = yaml.safe_dump(
        {"version": 2, "models": [model]}, sort_keys=False, width=1000, allow_unicode=True
    )
    return HEADER.format(entity=name) + body


def outputs(entities: list[dict[str, Any]]) -> dict[str, str]:
    """File name to text, for every `dbt` entity."""
    files: dict[str, str] = {}
    for entity in entities:
        if entity["built_by"] == "dbt":
            files[f"{entity['entity']}.sql"] = STUB.format(input=entity["input"])
            files[f"{entity['entity']}.yml"] = model_yml(entity)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m engine.dbt_models")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on a change")
    args: Any = parser.parse_args(argv)

    files = outputs(load_entities())
    changed = [n for n, text in files.items() if _read(OUT_DIR / n) != text]
    stale = sorted(p.name for p in OUT_DIR.glob("*") if p.name not in files)
    if not args.check:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for name in changed:
            (OUT_DIR / name).write_text(files[name], encoding="utf-8")
        for name in stale:
            (OUT_DIR / name).unlink()
    for name in changed:
        print(f"{'would change' if args.check else 'wrote'} {name}")
    for name in stale:
        print(f"{'would delete' if args.check else 'deleted'} {name}")
    return 1 if args.check and (changed or stale) else 0


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.exists() else None


if __name__ == "__main__":
    sys.exit(main())
