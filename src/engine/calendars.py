"""Generate the trading calendar files in reference/calendars/ (docs/specs/SW-17.md).

Run as `uv run python -m engine.calendars`. A file lists only the closures: weekdays without a
session. The libraries are dev dependencies; the pipeline reads the files and never runs this.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import exchange_calendars
import holidays
import pandas as pd

CALENDARS = ("XWAR", "NBP")
AD_HOC = "Ad hoc closure"
OUT_DIR = Path(__file__).resolve().parents[2] / "reference" / "calendars"
FIRST_YEAR = 2002
LAST_YEAR = 2027


@dataclass(frozen=True)
class Closure:
    date: date
    name: str


def file_name(calendar: str, year: int) -> str:
    return f"{calendar.lower()}_{year}.yaml"


def _weekdays(year: int) -> list[date]:
    day, days = date(year, 1, 1), []
    while day.year == year:
        if day.weekday() < 5:
            days.append(day)
        day += timedelta(days=1)
    return days


def _polish_holidays(year: int) -> dict[date, str]:
    return dict(holidays.country_holidays("PL", years=year, language="en_US").items())


def _xwar(year: int) -> tuple[exchange_calendars.ExchangeCalendar, dict[date, str]]:
    cal = exchange_calendars.get_calendar(
        "XWAR", start=pd.Timestamp(f"{FIRST_YEAR}-01-01"), end=pd.Timestamp(f"{LAST_YEAR}-12-31")
    )
    names: dict[date, str] = {}
    rules = cal.regular_holidays.holidays(
        pd.Timestamp(year, 1, 1), pd.Timestamp(year, 12, 31), return_name=True
    )
    for stamp, name in rules.items():
        names[stamp.date()] = str(name)
    return cal, names


def closures(calendar: str, year: int) -> list[Closure]:
    """Weekdays of `year` without a session of `calendar`, with a reason each."""
    if calendar not in CALENDARS:
        raise ValueError(f"unknown calendar {calendar!r}")
    polish = _polish_holidays(year)
    if calendar == "NBP":
        return [Closure(day, polish[day]) for day in _weekdays(year) if day in polish]

    cal, library_names = _xwar(year)
    start, end = pd.Timestamp(year, 1, 1), pd.Timestamp(year, 12, 31)
    sessions = {s.date() for s in cal.sessions if start <= s <= end}
    if any(day.weekday() >= 5 for day in sessions):
        raise ValueError(f"XWAR {year}: weekend session, the file format cannot express it")
    if len(cal.early_closes[(cal.early_closes >= start) & (cal.early_closes <= end)]):
        raise ValueError(f"XWAR {year}: early close, the file format cannot express it")
    return [
        Closure(day, polish.get(day) or library_names.get(day) or AD_HOC)
        for day in _weekdays(year)
        if day not in sessions
    ]


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(calendar: str, year: int, recorded_date: str, items: list[Closure]) -> str:
    lines = [
        f"# Trading calendar {calendar} {year}: weekdays without a session (ADR-005).",
        "# Generated by `python -m engine.calendars`; changes need Rafal's approval."
        " Schema: config/schemas/trading_calendar.schema.json.",
        "version: 1",
        f"calendar: {calendar}",
        f"year: {year}",
        f'recorded_date: "{recorded_date}"',
    ]
    if items:
        lines.append("closures:")
        for item in sorted(items, key=lambda c: c.date):
            lines.append(f'  - date: "{item.date.isoformat()}"')
            lines.append(f"    name: {_quote(item.name)}")
    else:
        lines.append("closures: []")
    return "\n".join(lines) + "\n"


def _recorded_date(path: Path) -> str | None:
    for line in path.read_text().splitlines():
        if line.startswith("recorded_date:"):
            return line.split('"')[1]
    return None


def build(calendar: str, year: int, out_dir: Path, recorded_date: str) -> tuple[Path, str]:
    """The path and text for one file; an unchanged file keeps its recorded date."""
    path = out_dir / file_name(calendar, year)
    items = closures(calendar, year)
    if path.exists():
        old = _recorded_date(path)
        if old is not None and path.read_text() == render(calendar, year, old, items):
            return path, path.read_text()
    return path, render(calendar, year, recorded_date, items)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m engine.calendars")
    parser.add_argument("--from-year", type=int, default=FIRST_YEAR)
    parser.add_argument("--to-year", type=int, default=LAST_YEAR)
    parser.add_argument("--recorded-date", default=date.today().isoformat())
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on a change")
    args: Any = parser.parse_args(argv)
    date.fromisoformat(args.recorded_date)

    changed: list[Path] = []
    for calendar in CALENDARS:
        for year in range(args.from_year, args.to_year + 1):
            path, text = build(calendar, year, args.out_dir, args.recorded_date)
            if path.exists() and path.read_text() == text:
                continue
            changed.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    for path in changed:
        print(f"{'would change' if args.check else 'wrote'} {path.name}")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
